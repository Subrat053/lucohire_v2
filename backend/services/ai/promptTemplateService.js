async function getPromptTemplate(key) {
  const dbTemplate = await prisma.aIPromptTemplate.findFirst({
    where: { key, isActive: true },
    orderBy: [{ updated_at: 'desc' }, { id: 'desc' }],
  });
  if (dbTemplate) {
    return {
      key,
      role: dbTemplate.role,
      template: dbTemplate.template,
      outputSchema: dbTemplate.outputSchema || {},
      temperature: Number(dbTemplate.temperature ?? 0.2),
      maxTokens: Number(dbTemplate.maxTokens ?? 800),
      source: 'db',
      version: Number(dbTemplate.version || 1),
    };
  }

  const fallback = DEFAULT_TEMPLATES[key] || {
    role: 'system',
    template: 'Return strict JSON with concise useful response.',
    temperature: 0.2,
    maxTokens: 700,
  };

  return {
    key,
    role: fallback.role,
    template: fallback.template,
    outputSchema: {},
    temperature: Number(fallback.temperature || 0.2),
    maxTokens: Number(fallback.maxTokens || 700),
    source: 'default',
    version: 1,
  };
}

